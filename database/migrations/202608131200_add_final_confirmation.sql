CREATE TABLE IF NOT EXISTS booking_final_confirmation (
  confirmation_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES booking(booking_id) ON DELETE CASCADE,
  match_id INTEGER NOT NULL REFERENCES vessel_match(match_id) ON DELETE RESTRICT,
  vessel_id INTEGER NOT NULL REFERENCES vessel(vessel_id) ON DELETE RESTRICT,
  port_id INTEGER NOT NULL REFERENCES port(port_id) ON DELETE RESTRICT,
  confirmation_actor_id INTEGER NOT NULL REFERENCES "user"(user_id) ON DELETE RESTRICT,
  confirmation_note TEXT,
  confirmed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  service_creation_status VARCHAR(20) NOT NULL DEFAULT 'CREATED',
  service_created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  shipment_id INTEGER NOT NULL UNIQUE REFERENCES shipment(shipment_id) ON DELETE RESTRICT,
  CONSTRAINT chk_confirmation_service_status CHECK (service_creation_status = 'CREATED')
