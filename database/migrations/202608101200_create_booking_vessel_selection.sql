BEGIN;

CREATE TABLE IF NOT EXISTS booking_vessel_selection (
  selection_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  booking_id INTEGER NOT NULL UNIQUE REFERENCES booking(booking_id) ON DELETE CASCADE,
  match_id INTEGER NOT NULL REFERENCES vessel_match(match_id) ON DELETE CASCADE,
  vessel_id INTEGER NOT NULL REFERENCES vessel(vessel_id) ON DELETE CASCADE,
  selection_note TEXT,
  selected_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_booking_vessel_selection_match_id
  ON booking_vessel_selection(match_id);

COMMIT;
